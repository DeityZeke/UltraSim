                            pendingEnd = runEnd;
                        }
                        else
                        {
                            ExecuteReadReadWriteRange(
                                route,
                                bound,
                                pendingStart,
                                pendingEnd - pendingStart,
                                ref visitor);
                            matchedRows += pendingEnd - pendingStart;
                            pendingStart = runStart;
                            pendingEnd = runEnd;
