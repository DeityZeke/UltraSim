            public void Compile(ArchetypeRegistry<TArena> registry)
            {
                global::System.ArgumentNullException.ThrowIfNull(registry);
                if (_compiledArchetypeCount == registry.Count)
                    return;

                int matchCount = 0;
                for (int index = 0; index < registry.Count; index++)
                {
                    ArchetypeStorage<TArena> storage = registry.GetStorage(new ArchetypeId((uint)index + 1));
                    if (Matches(storage, out _, out _, out _, out _))
                        matchCount++;
                }

                var routes = new ArchetypeReadReadChangedQueryRoute<TArena>[matchCount];
                int destination = 0;
                for (int index = 0; index < registry.Count; index++)
                {
                    ArchetypeStorage<TArena> storage = registry.GetStorage(new ArchetypeId((uint)index + 1));
                    if (!Matches(
                        storage,
                        out int read1ColumnIndex,
                        out int read2ColumnIndex,
                        out int changed1ColumnIndex,
                        out int changed2ColumnIndex))
                    {
                        continue;
                    }

                    ArchetypeQueryPlanUtilities.ValidateColumn<TRead1>(
                        storage.Columns[read1ColumnIndex],
                        Read1ComponentId,
                        _read1Flags);
                    ArchetypeQueryPlanUtilities.ValidateColumn<TRead2>(
                        storage.Columns[read2ColumnIndex],
                        Read2ComponentId,
                        _read2Flags);
                    ArchetypeQueryPlanUtilities.ValidateTrackedColumn(
                        storage.Columns[changed1ColumnIndex],
                        Changed1ComponentId,
                        _changed1Flags);
                    ArchetypeQueryPlanUtilities.ValidateTrackedColumn(
                        storage.Columns[changed2ColumnIndex],
                        Changed2ComponentId,
                        _changed2Flags);

                    SparseRowChangeVersions? changed1Rows = TracksExactRows
                        ? storage.Store.EnableSparseRowChangeTracking(changed1ColumnIndex)
                        : null;
                    SparseRowChangeVersions? changed2Rows = TracksExactRows
                        ? storage.Store.EnableSparseRowChangeTracking(changed2ColumnIndex)
                        : null;
                    routes[destination++] = new ArchetypeReadReadChangedQueryRoute<TArena>(
                        storage,
                        read1ColumnIndex,
                        read2ColumnIndex,
                        changed1ColumnIndex,
                        changed2ColumnIndex,
                        changed1Rows,
                        changed2Rows,
                        _enabledComponents,
                        _disabledComponents);
                }

                if (destination != routes.Length)
                {
                    ArchetypeQueryPlanUtilities.ThrowQueryInvariant(
                        "Generated changed-query match counting and route compilation disagree.");
                }
                _routes = routes;
                _compiledArchetypeCount = registry.Count;
            }

            public void Release()
            {
                _routes = [];
                _compiledArchetypeCount = -1;
            }

            private bool Matches(
                ArchetypeStorage<TArena> storage,
                out int read1ColumnIndex,
                out int read2ColumnIndex,
                out int changed1ColumnIndex,
                out int changed2ColumnIndex)
            {
                read1ColumnIndex = storage.Store.GetColumnIndex(Read1ComponentId);
                read2ColumnIndex = storage.Store.GetColumnIndex(Read2ComponentId);
                changed1ColumnIndex = storage.Store.GetColumnIndex(Changed1ComponentId);
                changed2ColumnIndex = storage.Store.GetColumnIndex(Changed2ComponentId);
                return read1ColumnIndex >= 0 &&
                    read2ColumnIndex >= 0 &&
                    changed1ColumnIndex >= 0 &&
                    changed2ColumnIndex >= 0 &&
                    ArchetypeQueryPlanUtilities.SignatureMatches(
                        storage.Signature,
                        _requiredComponents,
                        _excludedComponents);
            }
        }

