            public void Compile(ArchetypeRegistry<TArena> registry)
            {
                global::System.ArgumentNullException.ThrowIfNull(registry);
                if (_compiledArchetypeCount == registry.Count)
                    return;

                int matchCount = 0;
                for (int index = 0; index < registry.Count; index++)
                {
                    ArchetypeStorage<TArena> storage = registry.GetStorage(new ArchetypeId((uint)index + 1));
                    if (Matches(storage, out _, out _, out _))
                        matchCount++;
                }

                var routes = new ArchetypeReadReadWriteQueryRoute<TArena>[matchCount];
                int destination = 0;
                for (int index = 0; index < registry.Count; index++)
                {
                    ArchetypeStorage<TArena> storage = registry.GetStorage(new ArchetypeId((uint)index + 1));
                    if (!Matches(
                        storage,
                        out int read1ColumnIndex,
                        out int read2ColumnIndex,
                        out int writeColumnIndex))
                    {
                        continue;
                    }

                    ArchetypeQueryPlanUtilities.ValidateColumn<TRead1>(
                        storage.Columns[read1ColumnIndex],
                        Read1ComponentId,
                        _read1Flags);
                    ArchetypeQueryPlanUtilities.ValidateColumn<TRead2>(
                        storage.Columns[read2ColumnIndex],
                        Read2ComponentId,
                        _read2Flags);
                    ArchetypeQueryPlanUtilities.ValidateColumn<TWrite>(
                        storage.Columns[writeColumnIndex],
                        WriteComponentId,
                        _writeFlags);
                    routes[destination++] = new ArchetypeReadReadWriteQueryRoute<TArena>(
                        storage,
                        read1ColumnIndex,
                        read2ColumnIndex,
                        writeColumnIndex,
                        _enabledComponents,
                        _disabledComponents);
                }

                if (destination != routes.Length)
                {
                    ArchetypeQueryPlanUtilities.ThrowQueryInvariant(
                        "Generated query match counting and route compilation disagree.");
                }
                _routes = routes;
                _compiledArchetypeCount = registry.Count;
            }

            public void Release()
            {
                _routes = [];
                _compiledArchetypeCount = -1;
            }

