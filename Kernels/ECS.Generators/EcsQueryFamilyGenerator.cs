    private static void AppendVisitMethod(CodeWriter writer, QueryFamilySpec family)
    {
        writer.Line($"internal int Visit{family.Name}Chunks<{family.TypeParameters}, TVisitor>(");
        writer.Indent();
        writer.Line($"{family.PlanType}<TArena, {family.TypeParameters}> plan,");
        writer.Line("ref TVisitor visitor)");
        writer.Unindent();
        AppendComponentConstraints(writer, family);
        writer.Line($"where TVisitor : struct, {family.VisitorType}<{family.TypeParameters}>");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("EnsureSealed();");
        writer.Line($"Validate{family.Name}QueryPlan(plan);");
        writer.Line("EnterChunkVisit();");
        writer.Open("try");
        writer.Line("int visitedRows = 0;");
        writer.Line($"global::System.ReadOnlySpan<{family.RouteType}<TArena>> routes = plan.Routes;");
        writer.Open("for (int routeIndex = 0; routeIndex < routes.Length; routeIndex++)");
        writer.Line($"ref readonly {family.RouteType}<TArena> route = ref routes[routeIndex];");
        writer.Line("ArchetypeChunkStore<TArena> store = route.Storage.Store;");
        writer.Line("for (int chunkIndex = store.GetFirstOccupiedChunkIndex();");
        writer.Indent();
        writer.Line("chunkIndex >= 0;");
        writer.Line("chunkIndex = store.GetNextOccupiedChunkIndex(chunkIndex))");
        writer.Unindent();
        writer.Open(string.Empty, emitHeader: false);
        writer.Line($"{family.BoundChunkType}<{family.TypeParameters}> bound =");
        writer.Indent();
        writer.Line($"store.GetBound{family.Name}ComponentChunk<{family.TypeParameters}>(");
        writer.Indent();
        writer.Line("chunkIndex,");
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"route.{family.Slots[index].ColumnProperty},");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            string suffix = index == family.Slots.Length - 1 ? ");" : ",";
            writer.Line($"plan.{family.Slots[index].PlanIsEnableableProperty}{suffix}");
        }
        writer.Unindent();
        writer.Unindent();
        writer.Open("if (!route.HasRowFilters)");
        writer.Line($"var chunk = new {family.ChunkType}<{family.TypeParameters}>(");
        writer.Indent();
        writer.Line("Id,");
        writer.Line("route.Storage.Id,");
        writer.Line("bound.ChunkIndex,");
        writer.Line("rowOffset: 0,");
        writer.Line("bound.EntityIndices,");
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"bound.{family.Slots[index].ComponentsProperty},");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            string suffix = index == family.Slots.Length - 1 ? ");" : ",";
            writer.Line($"bound.{family.Slots[index].EnableProperty}{suffix}");
        }
        writer.Unindent();
        writer.Line("visitor.Execute(in chunk);");
        writer.Line("visitedRows += chunk.Count;");
        writer.Close();
        writer.Open("else");
        writer.Line($"visitedRows += VisitFiltered{family.Name}Chunk(");
        writer.Indent();
        writer.Line("route,");
        writer.Line("bound,");
        writer.Line("ref visitor);");
        writer.Unindent();
        writer.Close();
        writer.Close();
        writer.Close();
        writer.Line("return visitedRows;");
        writer.Close();
        writer.Open("finally");
        writer.Line("ExitChunkVisit();");
        writer.Close();
        writer.Close();
    }

    private static void AppendFilteredVisitMethod(CodeWriter writer, QueryFamilySpec family)
    {
        AppendMethodImpl(writer, "global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization");
        writer.Line($"private int VisitFiltered{family.Name}Chunk<{family.TypeParameters}, TVisitor>(");
        writer.Indent();
        writer.Line($"in {family.RouteType}<TArena> route,");
        writer.Line($"in {family.BoundChunkType}<{family.TypeParameters}> bound,");
        writer.Line("ref TVisitor visitor)");
        writer.Unindent();
        AppendComponentConstraints(writer, family);
        writer.Line($"where TVisitor : struct, {family.VisitorType}<{family.TypeParameters}>");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("int rowCount = bound.EntityIndices.Length;");
        writer.Line("int pendingStart = -1;");
        writer.Line("int pendingEnd = -1;");
        writer.Line("int matchedRows = 0;");
        writer.Line("int wordCount = (rowCount + 63) >> 6;");
        writer.Open("for (int wordIndex = 0; wordIndex < wordCount; wordIndex++)");
        writer.Line("ulong mask = route.GetMatchingRowMask(bound.ChunkBytes, wordIndex);");
        writer.Line("int wordStart = wordIndex << 6;");
        writer.Line("int activeRows = global::System.Math.Min(64, rowCount - wordStart);");
        writer.Line("if (activeRows != 64)");
        writer.Indent();
        writer.Line("mask &= (1UL << activeRows) - 1UL;");
        writer.Unindent();
        writer.Line();
        writer.Open("while (mask != 0)");
        writer.Line("int startBit = global::System.Numerics.BitOperations.TrailingZeroCount(mask);");
        writer.Line("ulong shifted = mask >> startBit;");
        writer.Line("int runLength = global::System.Numerics.BitOperations.TrailingZeroCount(~shifted);");
        writer.Line("int runStart = wordStart + startBit;");
        writer.Line("int runEnd = runStart + runLength;");
        writer.Open("if (pendingStart < 0)");
        writer.Line("pendingStart = runStart;");
        writer.Line("pendingEnd = runEnd;");
        writer.Close();
        writer.Open("else if (pendingEnd == runStart)");
        writer.Line("pendingEnd = runEnd;");
        writer.Close();
        writer.Open("else");
        writer.Line($"Execute{family.Name}Range(");
        writer.Indent();
        writer.Line("route,");
        writer.Line("bound,");
        writer.Line("pendingStart,");
        writer.Line("pendingEnd - pendingStart,");
        writer.Line("ref visitor);");
        writer.Unindent();
        writer.Line("matchedRows += pendingEnd - pendingStart;");
        writer.Line("pendingStart = runStart;");
        writer.Line("pendingEnd = runEnd;");
        writer.Close();
        writer.Line();
        writer.Line("ulong runMask = runLength == 64");
        writer.Indent();
        writer.Line("? ulong.MaxValue");
        writer.Line(": ((1UL << runLength) - 1UL) << startBit;");
        writer.Unindent();
        writer.Line("mask &= ~runMask;");
        writer.Close();
        writer.Close();
        writer.Line();
        writer.Open("if (pendingStart >= 0)");
        writer.Line($"Execute{family.Name}Range(");
        writer.Indent();
        writer.Line("route,");
        writer.Line("bound,");
        writer.Line("pendingStart,");
        writer.Line("pendingEnd - pendingStart,");
        writer.Line("ref visitor);");
        writer.Unindent();
        writer.Line("matchedRows += pendingEnd - pendingStart;");
        writer.Close();
        writer.Line("return matchedRows;");
        writer.Close();
    }

