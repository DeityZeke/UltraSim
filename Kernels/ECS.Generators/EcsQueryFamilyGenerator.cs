    private sealed class AccessSlot
    {
        internal AccessSlot(bool isWrite, int ordinal, int accessCount)
        {
            IsWrite = isWrite;
            AccessOrdinal = ordinal;
            string access = isWrite ? "Write" : "Read";
            string suffix = accessCount == 1 ? string.Empty : ordinal.ToString();
            Name = access + suffix;
            CamelName = char.ToLowerInvariant(Name[0]) + Name.Substring(1);
            TypeName = "T" + Name;
            ComponentsProperty = access + "Components" + suffix;
        }

        internal bool IsWrite { get; }
        internal int AccessOrdinal { get; }
        internal string Name { get; }
        internal string CamelName { get; }
        internal string TypeName { get; }
        internal string ComponentSpanType => IsWrite
            ? "global::System.Span"
            : "global::System.ReadOnlySpan";
        internal string EnableSpanType => IsWrite
            ? "global::System.Span<ulong>"
            : "global::System.ReadOnlySpan<ulong>";
        internal string ComponentsParameter => CamelName + "Components";
        internal string ComponentsProperty { get; }
        internal string EnableParameter => CamelName + "EnableWords";
        internal string EnableField => "_" + EnableParameter;
        internal string EnableProperty => Name + "EnableWords";
        internal string IsEnableableProperty => "Is" + Name + "Enableable";
        internal string PlanIsEnableableProperty => Name + "IsEnableable";
        internal string IsEnabledMethod => "Is" + Name + "Enabled";
        internal string SetEnabledMethod => "Set" + Name + "Enabled";
        internal string ComponentIdParameter => CamelName + "ComponentId";
        internal string GeneratedComponentIdParameter => "generated" + Name + "ComponentId";
        internal string ComponentIdProperty => Name + "ComponentId";
        internal string FlagsParameter => CamelName + "Flags";
        internal string FlagsField => "_" + FlagsParameter;
        internal string ColumnParameter => CamelName + "ColumnIndex";
        internal string ColumnProperty => Name + "ColumnIndex";
        internal string ColumnLocal => CamelName + "Column";
        internal string IncludeEnableParameter => "include" + Name + "EnableWords";
        internal string MetadataLocal => CamelName + "Metadata";
    }

    private sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new StringBuilder(48 * 1024);
        private int _indent;

        internal void Line(string text = "")
        {
            if (text.Length != 0)
                _builder.Append(' ', _indent * 4);
            _builder.AppendLine(text);
        }

        internal void Open(string header, bool emitHeader = true)
        {
            if (emitHeader)
                Line(header);
            Line("{");
            _indent++;
        }

        internal void Close()
        {
            _indent--;
            Line("}");
        }

        internal void Indent() => _indent++;

        internal void Unindent() => _indent--;

        public override string ToString() => _builder.ToString();
    }
