    private static void AppendMethodImpl(CodeWriter writer, string options)
    {
        writer.Line("[global::System.Runtime.CompilerServices.MethodImpl(");
        writer.Indent();
        string[] lines = options.Split(new[] { '\n' }, StringSplitOptions.None);
        for (int index = 0; index < lines.Length; index++)
        {
            string suffix = index == lines.Length - 1 ? ")]" : string.Empty;
            writer.Line(lines[index] + suffix);
        }
        writer.Unindent();
    }

    private static string BuildDistinctCondition(
        QueryFamilySpec family,
        Func<AccessSlot, string> selector) =>
        string.Join(" ||\n            ", BuildPairConditions(family, (left, right) =>
            selector(left) + " == " + selector(right)));

    private static IEnumerable<string> BuildPairConditions(
        QueryFamilySpec family,
        Func<AccessSlot, string> selector) =>
        BuildPairConditions(family, (left, right) => selector(left) + " != " + selector(right));

    private static IEnumerable<string> BuildPairConditions(
        QueryFamilySpec family,
        Func<AccessSlot, AccessSlot, string> selector)
    {
        for (int left = 0; left < family.Slots.Length; left++)
        {
            for (int right = left + 1; right < family.Slots.Length; right++)
                yield return selector(family.Slots[left], family.Slots[right]);
        }
    }

    private sealed class QueryFamilySpec
    {
        internal QueryFamilySpec(int readCount, int writeCount)
        {
            if (readCount <= 0)
                throw new ArgumentOutOfRangeException(nameof(readCount));
            if (writeCount <= 0)
                throw new ArgumentOutOfRangeException(nameof(writeCount));

            ReadCount = readCount;
            WriteCount = writeCount;
            var slots = new List<AccessSlot>(readCount + writeCount);
            for (int ordinal = 1; ordinal <= readCount; ordinal++)
                slots.Add(new AccessSlot(isWrite: false, ordinal, readCount));
            for (int ordinal = 1; ordinal <= writeCount; ordinal++)
                slots.Add(new AccessSlot(isWrite: true, ordinal, writeCount));
            Slots = slots.ToArray();
            Name = string.Concat(
                Enumerable.Repeat("Read", readCount).Concat(Enumerable.Repeat("Write", writeCount)));
            TypeParameters = string.Join(", ", Slots.Select(static slot => slot.TypeName));
        }

        internal int ReadCount { get; }
        internal int WriteCount { get; }
        internal AccessSlot[] Slots { get; }
        internal string Name { get; }
        internal string TypeParameters { get; }
        internal string Summary => $"{ReadCount} read column{(ReadCount == 1 ? string.Empty : "s")} and {WriteCount} write column{(WriteCount == 1 ? string.Empty : "s")}";
        internal string HintName => $"UltraSim.ECS.QueryFamilies.{ReadCount}R{WriteCount}W.g.cs";
        internal string VisitorType => "IComponentChunk" + Name + "Visitor";
        internal string ChunkType => Name + "ComponentChunk";
        internal string BoundChunkType => "Bound" + Name + "ComponentChunk";
        internal string RouteType => "Archetype" + Name + "QueryRoute";
        internal string PlanType => "Archetype" + Name + "QueryPlan";
    }

    private sealed class AccessSlot
    {
        internal AccessSlot(bool isWrite, int ordinal, int accessCount)
        {
            IsWrite = isWrite;
            AccessOrdinal = ordinal;
            string access = isWrite ? "Write" : "Read";
            string suffix = accessCount == 1 ? string.Empty : ordinal.ToString();
            Name = access + suffix;
            CamelName = char.ToLowerInvariant(Name[0]) + Name.Substring(1);
            TypeName = "T" + Name;
            ComponentsProperty = access + "Components" + suffix;
        }

        internal bool IsWrite { get; }
        internal int AccessOrdinal { get; }
        internal string Name { get; }
        internal string CamelName { get; }
        internal string TypeName { get; }
        internal string ComponentSpanType => IsWrite
            ? "global::System.Span"
            : "global::System.ReadOnlySpan";
        internal string EnableSpanType => IsWrite
            ? "global::System.Span<ulong>"
            : "global::System.ReadOnlySpan<ulong>";
        internal string ComponentsParameter => CamelName + "Components";
        internal string ComponentsProperty { get; }
        internal string EnableParameter => CamelName + "EnableWords";
        internal string EnableField => "_" + EnableParameter;
        internal string EnableProperty => Name + "EnableWords";
        internal string IsEnableableProperty => "Is" + Name + "Enableable";
        internal string PlanIsEnableableProperty => Name + "IsEnableable";
        internal string IsEnabledMethod => "Is" + Name + "Enabled";
        internal string SetEnabledMethod => "Set" + Name + "Enabled";
        internal string ComponentIdParameter => CamelName + "ComponentId";
        internal string GeneratedComponentIdParameter => "generated" + Name + "ComponentId";
        internal string ComponentIdProperty => Name + "ComponentId";
        internal string FlagsParameter => CamelName + "Flags";
        internal string FlagsField => "_" + FlagsParameter;
        internal string ColumnParameter => CamelName + "ColumnIndex";
        internal string ColumnProperty => Name + "ColumnIndex";
        internal string ColumnLocal => CamelName + "Column";
        internal string IncludeEnableParameter => "include" + Name + "EnableWords";
        internal string MetadataLocal => CamelName + "Metadata";
    }

    private sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new StringBuilder(48 * 1024);
        private int _indent;

        internal void Line(string text = "")
        {
            if (text.Length != 0)
                _builder.Append(' ', _indent * 4);
            _builder.AppendLine(text);
        }

        internal void Open(string header, bool emitHeader = true)
        {
            if (emitHeader)
                Line(header);
            Line("{");
            _indent++;
        }

        internal void Close()
        {
            _indent--;
            Line("}");
        }

        internal void Indent() => _indent++;

        internal void Unindent() => _indent--;

        public override string ToString() => _builder.ToString();
    }
