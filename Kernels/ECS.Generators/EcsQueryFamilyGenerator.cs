            [global::System.Runtime.CompilerServices.MethodImpl(
                global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization)]
            private int VisitExactReadReadChangedChunk<TRead1, TRead2, TVisitor>(
                in ArchetypeReadReadChangedQueryRoute<TArena> route,
                in BoundReadReadComponentChunk<TRead1, TRead2> bound,
                ChangeVersion baseline,
                ChangedMatchMode matchMode,
                ref TVisitor visitor)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
                where TVisitor : struct, IComponentChunkReadReadVisitor<TRead1, TRead2>
            {
                int rowCount = bound.EntityIndices.Length;
                int pendingStart = -1;
                int pendingEnd = -1;
                int matchedRows = 0;
                int wordCount = (rowCount + 63) >> 6;
                for (int wordIndex = 0; wordIndex < wordCount; wordIndex++)
                {
                    int wordStart = wordIndex << 6;
                    int activeRows = global::System.Math.Min(64, rowCount - wordStart);
                    ulong mask = route.GetChangedRowMask(
                        bound.ChunkIndex,
                        wordIndex,
                        activeRows,
                        baseline,
                        matchMode);
                    if (route.HasRowFilters)
                        mask &= route.GetMatchingRowMask(bound.ChunkBytes, wordIndex);
                    CollectReadReadChangedRanges(
                        route,
                        bound,
                        wordStart,
                        mask,
                        ref pendingStart,
                        ref pendingEnd,
                        ref matchedRows,
                        ref visitor);
                }

                if (pendingStart >= 0)
                {
                    ExecuteReadReadChangedRange(
                        route,
                        bound,
                        pendingStart,
                        pendingEnd - pendingStart,
                        ref visitor);
                    matchedRows += pendingEnd - pendingStart;
                }
                return matchedRows;
            }

            [global::System.Runtime.CompilerServices.MethodImpl(
                global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization)]
            private int VisitFilteredReadReadChangedChunk<TRead1, TRead2, TVisitor>(
                in ArchetypeReadReadChangedQueryRoute<TArena> route,
                in BoundReadReadComponentChunk<TRead1, TRead2> bound,
                ref TVisitor visitor)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
                where TVisitor : struct, IComponentChunkReadReadVisitor<TRead1, TRead2>
            {
                int rowCount = bound.EntityIndices.Length;
                int pendingStart = -1;
                int pendingEnd = -1;
                int matchedRows = 0;
                int wordCount = (rowCount + 63) >> 6;
                for (int wordIndex = 0; wordIndex < wordCount; wordIndex++)
                {
                    ulong mask = route.GetMatchingRowMask(bound.ChunkBytes, wordIndex);
                    int wordStart = wordIndex << 6;
                    int activeRows = global::System.Math.Min(64, rowCount - wordStart);
                    if (activeRows != 64)
                        mask &= (1UL << activeRows) - 1UL;
                    CollectReadReadChangedRanges(
                        route,
                        bound,
                        wordStart,
                        mask,
                        ref pendingStart,
                        ref pendingEnd,
                        ref matchedRows,
                        ref visitor);
                }

                if (pendingStart >= 0)
                {
                    ExecuteReadReadChangedRange(
                        route,
                        bound,
                        pendingStart,
                        pendingEnd - pendingStart,
                        ref visitor);
                    matchedRows += pendingEnd - pendingStart;
                }
                return matchedRows;
            }

            [global::System.Runtime.CompilerServices.MethodImpl(
                global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
            private void CollectReadReadChangedRanges<TRead1, TRead2, TVisitor>(
                in ArchetypeReadReadChangedQueryRoute<TArena> route,
                in BoundReadReadComponentChunk<TRead1, TRead2> bound,
                int wordStart,
                ulong mask,
                ref int pendingStart,
                ref int pendingEnd,
                ref int matchedRows,
                ref TVisitor visitor)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
                where TVisitor : struct, IComponentChunkReadReadVisitor<TRead1, TRead2>
            {
                while (mask != 0)
                {
                    int startBit = global::System.Numerics.BitOperations.TrailingZeroCount(mask);
                    ulong shifted = mask >> startBit;
                    int runLength = global::System.Numerics.BitOperations.TrailingZeroCount(~shifted);
                    int runStart = wordStart + startBit;
                    int runEnd = runStart + runLength;
                    if (pendingStart < 0)
                    {
                        pendingStart = runStart;
                        pendingEnd = runEnd;
                    }
                    else if (pendingEnd == runStart)
                    {
                        pendingEnd = runEnd;
                    }
                    else
                    {
                        ExecuteReadReadChangedRange(
                            route,
                            bound,
                            pendingStart,
                            pendingEnd - pendingStart,
                            ref visitor);
                        matchedRows += pendingEnd - pendingStart;
                        pendingStart = runStart;
                        pendingEnd = runEnd;
                    }

                    ulong runMask = runLength == 64
                        ? ulong.MaxValue
                        : ((1UL << runLength) - 1UL) << startBit;
                    mask &= ~runMask;
                }
            }

