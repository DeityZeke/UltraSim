            internal int VisitReadReadWriteChunks<TRead1, TRead2, TWrite, TVisitor>(
                ArchetypeReadReadWriteQueryPlan<TArena, TRead1, TRead2, TWrite> plan,
                ref TVisitor visitor)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
                where TWrite : unmanaged, IComponent<TWrite>
                where TVisitor : struct, IComponentChunkReadReadWriteVisitor<TRead1, TRead2, TWrite>
            {
                EnsureSealed();
                ValidateGeneratedQueryPlan(plan);
                EnterChunkVisit();
                try
                {
                    int visitedRows = 0;
                    global::System.ReadOnlySpan<ArchetypeReadReadWriteQueryRoute<TArena>> routes = plan.Routes;
                    for (int routeIndex = 0; routeIndex < routes.Length; routeIndex++)
                    {
                        ref readonly ArchetypeReadReadWriteQueryRoute<TArena> route = ref routes[routeIndex];
                        ArchetypeChunkStore<TArena> store = route.Storage.Store;
                        for (int chunkIndex = store.GetFirstOccupiedChunkIndex();
                             chunkIndex >= 0;
                             chunkIndex = store.GetNextOccupiedChunkIndex(chunkIndex))
                        {
                            BoundReadReadWriteComponentChunk<TRead1, TRead2, TWrite> bound =
                                store.GetBoundReadReadWriteComponentChunk<TRead1, TRead2, TWrite>(
                                    chunkIndex,
                                    route.Read1ColumnIndex,
                                    route.Read2ColumnIndex,
                                    route.WriteColumnIndex,
                                    plan.Read1IsEnableable,
                                    plan.Read2IsEnableable,
                                    plan.WriteIsEnableable);
                            if (!route.HasRowFilters)
                            {
                                var chunk = new ReadReadWriteComponentChunk<TRead1, TRead2, TWrite>(
                                    Id,
                                    route.Storage.Id,
                                    bound.ChunkIndex,
                                    rowOffset: 0,
                                    bound.EntityIndices,
                                    bound.ReadComponents1,
                                    bound.ReadComponents2,
                                    bound.WriteComponents,
                                    bound.Read1EnableWords,
                                    bound.Read2EnableWords,
                                    bound.WriteEnableWords);
                                visitor.Execute(in chunk);
                                visitedRows += chunk.Count;
                            }
                            else
                            {
                                visitedRows += VisitFilteredReadReadWriteChunk(
                                    route,
                                    bound,
                                    ref visitor);
                            }
                        }
                    }
                    return visitedRows;
                }
                finally
                {
                    ExitChunkVisit();
                }
            }

            [global::System.Runtime.CompilerServices.MethodImpl(
                global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization)]
            private int VisitFilteredReadReadWriteChunk<TRead1, TRead2, TWrite, TVisitor>(
                in ArchetypeReadReadWriteQueryRoute<TArena> route,
                in BoundReadReadWriteComponentChunk<TRead1, TRead2, TWrite> bound,
                ref TVisitor visitor)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
