            private ArchetypeReadReadChangedQueryPlan<TArena, TRead1, TRead2>
                PrepareReadReadChangedQuery<TRead1, TRead2>(
                    ComponentId generatedRead1ComponentId,
                    ComponentId generatedRead2ComponentId,
                    ComponentId changed1ComponentId,
                    ComponentId changed2ComponentId,
                    ChangedMatchMode matchMode,
                    in ArchetypeQueryFilter filter,
                    bool tracksExactRows)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
            {
                EnsureCreated();
                if (!filter.IsValid || filter.WorldId != Id)
                    throw new global::System.ArgumentException("The query filter belongs to a different world.", nameof(filter));
                if (matchMode is not (ChangedMatchMode.Any or ChangedMatchMode.All))
                    throw new global::System.ArgumentOutOfRangeException(nameof(matchMode));

                ref readonly ComponentMetadata read1Metadata = ref ValidateGeneratedDataComponent<TRead1>(
                    generatedRead1ComponentId,
                    nameof(generatedRead1ComponentId));
                ref readonly ComponentMetadata read2Metadata = ref ValidateGeneratedDataComponent<TRead2>(
                    generatedRead2ComponentId,
                    nameof(generatedRead2ComponentId));
                ref readonly ComponentMetadata changed1Metadata = ref ValidateTrackedComponent(
                    changed1ComponentId,
                    nameof(changed1ComponentId));
                ref readonly ComponentMetadata changed2Metadata = ref ValidateTrackedComponent(
                    changed2ComponentId,
                    nameof(changed2ComponentId));
                if (generatedRead1ComponentId == generatedRead2ComponentId)
                    throw new global::System.ArgumentException("Generated read columns must be distinct.");
                if (changed1ComponentId == changed2ComponentId)
                    throw new global::System.ArgumentException("Generated watched columns must be distinct.");
                if (filter.Excludes(generatedRead1ComponentId) ||
                    filter.Excludes(generatedRead2ComponentId) ||
                    filter.Excludes(changed1ComponentId) ||
                    filter.Excludes(changed2ComponentId))
                {
                    throw new global::System.ArgumentException(
                        "A read or watched component cannot also be excluded by its query filter.",
                        nameof(filter));
                }
                if (_queryPlanCount == _queryPlans.Length)
                {
                    throw new global::System.InvalidOperationException(
                        $"Query-plan capacity {_queryPlans.Length} is exhausted.");
                }

                var plan = new ArchetypeReadReadChangedQueryPlan<TArena, TRead1, TRead2>(
                    Id,
                    _queryPlanCount,
                    generatedRead1ComponentId,
                    read1Metadata.Flags,
                    generatedRead2ComponentId,
                    read2Metadata.Flags,
                    changed1ComponentId,
                    changed1Metadata.Flags,
                    changed2ComponentId,
                    changed2Metadata.Flags,
                    matchMode,
                    tracksExactRows,
                    filter);
                _queryPlans[_queryPlanCount++] = plan;
                return plan;
            }

            internal int VisitReadReadChangedChunks<TRead1, TRead2, TVisitor>(
                ArchetypeReadReadChangedQueryPlan<TArena, TRead1, TRead2> plan,
                ref ChangeCursor cursor,
                ref TVisitor visitor)
                where TRead1 : unmanaged, IComponent<TRead1>
                where TRead2 : unmanaged, IComponent<TRead2>
                where TVisitor : struct, IComponentChunkReadReadVisitor<TRead1, TRead2>
            {
                EnsureSealed();
                ValidateReadReadChangedQueryPlan(plan);
                ValidateChangeCursor(cursor);
                ChangeVersion observationVersion = _changeVersion;
                ChangeVersion baseline = cursor.Version;
                EnterChunkVisit();
                try
                {
                    int visitedRows = 0;
                    global::System.ReadOnlySpan<ArchetypeReadReadChangedQueryRoute<TArena>> routes = plan.Routes;
                    for (int routeIndex = 0; routeIndex < routes.Length; routeIndex++)
                    {
                        ref readonly ArchetypeReadReadChangedQueryRoute<TArena> route = ref routes[routeIndex];
                        ArchetypeChunkStore<TArena> store = route.Storage.Store;
                        for (int chunkIndex = store.GetFirstOccupiedChunkIndex();
                             chunkIndex >= 0;
                             chunkIndex = store.GetNextOccupiedChunkIndex(chunkIndex))
                        {
                            uint occupiedChunkIndex = (uint)chunkIndex;
                            if (!route.HasChunkChangedSince(
                                occupiedChunkIndex,
                                baseline,
                                plan.MatchMode))
                            {
                                continue;
                            }

                            BoundReadReadComponentChunk<TRead1, TRead2> bound =
                                store.GetBoundReadReadComponentChunk<TRead1, TRead2>(
                                    chunkIndex,
                                    route.Read1ColumnIndex,
                                    route.Read2ColumnIndex,
                                    plan.Read1IsEnableable,
                                    plan.Read2IsEnableable);
                            if (!route.HasRowFilters)
                            {
                                var chunk = new ReadReadComponentChunk<TRead1, TRead2>(
                                    Id,
                                    route.Storage.Id,
                                    bound.ChunkIndex,
                                    rowOffset: 0,
                                    bound.EntityIndices,
                                    bound.ReadComponents1,
                                    bound.ReadComponents2,
                                    bound.Read1EnableWords,
                                    bound.Read2EnableWords);
                                visitor.Execute(in chunk);
                                visitedRows += chunk.Count;
                            }
                            else
                            {
                                visitedRows += VisitFilteredReadReadChangedChunk(
                                    route,
                                    bound,
                                    ref visitor);
                            }
                        }
                    }

                    cursor = cursor.AdvanceTo(observationVersion);
                    return visitedRows;
                }
                finally
                {
                    ExitChunkVisit();
                }
            }

            internal int VisitReadReadChangedRows<TRead1, TRead2, TVisitor>(
