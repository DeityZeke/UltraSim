                    read2ColumnIndex >= 0 &&
                    writeColumnIndex >= 0 &&
                    ArchetypeQueryPlanUtilities.SignatureMatches(
                        storage.Signature,
                        _requiredComponents,
                        _excludedComponents);
            }
        }

