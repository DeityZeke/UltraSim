        writer.Open(string.Empty, emitHeader: false);
        writer.Line($"internal {family.BoundChunkType}(");
        writer.Indent();
        writer.Line("uint chunkIndex,");
        writer.Line("global::System.ReadOnlySpan<byte> chunkBytes,");
        writer.Line("global::System.ReadOnlySpan<uint> entityIndices,");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"{slot.ComponentSpanType}<{slot.TypeName}> {slot.ComponentsParameter},");
        }
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            string suffix = index == family.Slots.Length - 1 ? ")" : ",";
            writer.Line($"{slot.EnableSpanType} {slot.EnableParameter}{suffix}");
        }
        writer.Unindent();
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("ChunkIndex = chunkIndex;");
        writer.Line("ChunkBytes = chunkBytes;");
        writer.Line("EntityIndices = entityIndices;");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"{slot.ComponentsProperty} = {slot.ComponentsParameter};");
            writer.Line($"{slot.EnableProperty} = {slot.EnableParameter};");
        }
        writer.Close();
        writer.Line();
        writer.Line("internal uint ChunkIndex { get; }");
        writer.Line("internal global::System.ReadOnlySpan<byte> ChunkBytes { get; }");
        writer.Line("internal global::System.ReadOnlySpan<uint> EntityIndices { get; }");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"internal {slot.ComponentSpanType}<{slot.TypeName}> {slot.ComponentsProperty} {{ get; }}");
            writer.Line($"internal {slot.EnableSpanType} {slot.EnableProperty} {{ get; }}");
        }
        writer.Close();
    }

    private static void AppendRoute(CodeWriter writer, QueryFamilySpec family)
    {
        writer.Line($"/// <summary>Generated physical route for a {family.Summary} query.</summary>");
        writer.Line($"internal readonly struct {family.RouteType}<TArena>");
        writer.Line("where TArena : class, IChunkArenaBackend");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line($"internal {family.RouteType}(");
        writer.Indent();
        writer.Line("ArchetypeStorage<TArena> storage,");
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"int {family.Slots[index].ColumnParameter},");
        writer.Line("global::System.ReadOnlySpan<ComponentId> enabledComponents,");
        writer.Line("global::System.ReadOnlySpan<ComponentId> disabledComponents)");
        writer.Unindent();
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(storage);");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"if (unchecked((uint){slot.ColumnParameter}) >= ushort.MaxValue)");
            writer.Indent();
            writer.Line($"throw new global::System.ArgumentOutOfRangeException(nameof({slot.ColumnParameter}));");
            writer.Unindent();
        }
        writer.Line($"if ({BuildDistinctCondition(family, static slot => slot.ColumnParameter)})");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("throw new global::System.ArgumentException(\"Generated query columns must not alias.\");");
        writer.Close();
        writer.Line("Storage = storage;");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"{slot.ColumnProperty} = (ushort){slot.ColumnParameter};");
        }
        writer.Line("RowFilter = ArchetypeQueryRowFilter.Bind(");
        writer.Indent();
        writer.Line("storage,");
        writer.Line("enabledComponents,");
        writer.Line("disabledComponents);");
        writer.Unindent();
        writer.Close();
        writer.Line();
        writer.Line("internal ArchetypeStorage<TArena> Storage { get; }");
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"internal int {family.Slots[index].ColumnProperty} {{ get; }}");
        writer.Line("private ArchetypeQueryRowFilter RowFilter { get; }");
        writer.Line("internal bool HasRowFilters => RowFilter.HasFilters;");
        writer.Line("internal ulong GetMatchingRowMask(global::System.ReadOnlySpan<byte> chunkBytes, int wordIndex) =>");
        writer.Indent();
        writer.Line("RowFilter.GetMatchingRowMask(chunkBytes, wordIndex);");
        writer.Unindent();
        writer.Close();
    }

    private static void AppendPlan(CodeWriter writer, QueryFamilySpec family)
    {
        writer.Line($"/// <summary>Generated seal-compiled plan with {family.Summary}.</summary>");
        writer.Line($"internal sealed class {family.PlanType}<TArena, {family.TypeParameters}> :");
        writer.Indent();
        writer.Line("IArchetypeQueryPlan<TArena>");
        writer.Unindent();
        writer.Line("where TArena : class, IChunkArenaBackend");
        AppendComponentConstraints(writer, family);
        writer.Open(string.Empty, emitHeader: false);
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"private readonly ComponentFlags {family.Slots[index].FlagsField};");
        writer.Line("private readonly ComponentId[] _requiredComponents;");
        writer.Line("private readonly ComponentId[] _excludedComponents;");
        writer.Line("private readonly ComponentId[] _enabledComponents;");
        writer.Line("private readonly ComponentId[] _disabledComponents;");
        writer.Line($"private {family.RouteType}<TArena>[] _routes = [];");
        writer.Line("private int _compiledArchetypeCount = -1;");
        writer.Line();
        writer.Line($"internal {family.PlanType}(");
        writer.Indent();
        writer.Line("WorldId worldId,");
        writer.Line("int planIndex,");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"ComponentId {slot.ComponentIdParameter},");
            writer.Line($"ComponentFlags {slot.FlagsParameter},");
        }
        writer.Line("in ArchetypeQueryFilter filter)");
        writer.Unindent();
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("if (!worldId.IsValid)");
        writer.Indent();
        writer.Line("throw new global::System.ArgumentException(\"A valid world ID is required.\", nameof(worldId));");
        writer.Unindent();
        writer.Line("if (planIndex < 0)");
        writer.Indent();
        writer.Line("throw new global::System.ArgumentOutOfRangeException(nameof(planIndex));");
        writer.Unindent();
        writer.Line($"if ({string.Join(" || ", family.Slots.Select(static slot => "!" + slot.ComponentIdParameter + ".IsValid"))})");
        writer.Indent();
        writer.Line("throw new global::System.ArgumentException(\"Valid generated component IDs are required.\");");
        writer.Unindent();
        writer.Line($"if ({BuildDistinctCondition(family, static slot => slot.ComponentIdParameter)})");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("throw new global::System.ArgumentException(\"Generated query access components must be distinct.\");");
        writer.Close();
        writer.Line($"if ((({string.Join(" | ", family.Slots.Select(static slot => slot.FlagsParameter))}) & ComponentFlags.Tag) != 0)");
        writer.Indent();
        writer.Line("throw new global::System.ArgumentException(\"Data query columns cannot be storage-free tags.\");");
        writer.Unindent();
        writer.Line();
        writer.Line("WorldId = worldId;");
        writer.Line("PlanIndex = planIndex;");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"{slot.ComponentIdProperty} = {slot.ComponentIdParameter};");
            writer.Line($"{slot.FlagsField} = {slot.FlagsParameter};");
        }
        writer.Line("_requiredComponents = ArchetypeQueryPlanUtilities.MergeRequiredComponents(");
        writer.Indent();
        writer.Line($"[{string.Join(", ", family.Slots.Select(static slot => slot.ComponentIdParameter))}],");
        writer.Line("filter.RequiredComponents);");
        writer.Unindent();
        writer.Line("_excludedComponents = filter.ExcludedComponents.ToArray();");
        writer.Line("_enabledComponents = filter.EnabledComponents.ToArray();");
        writer.Line("_disabledComponents = filter.DisabledComponents.ToArray();");
        writer.Close();
        writer.Line();
        writer.Line("internal WorldId WorldId { get; }");
        writer.Line("internal int PlanIndex { get; }");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"internal ComponentId {slot.ComponentIdProperty} {{ get; }}");
            writer.Line($"internal bool {slot.PlanIsEnableableProperty} => ({slot.FlagsField} & ComponentFlags.Enableable) != 0;");
        }
        writer.Line("internal bool IsCompiled => _compiledArchetypeCount >= 0;");
        writer.Line("internal int MatchedArchetypeCount => _routes.Length;");
        writer.Line("internal global::System.ReadOnlySpan<ComponentId> RequiredComponents => _requiredComponents;");
        writer.Line("internal global::System.ReadOnlySpan<ComponentId> ExcludedComponents => _excludedComponents;");
        writer.Line("internal global::System.ReadOnlySpan<ComponentId> EnabledComponents => _enabledComponents;");
        writer.Line("internal global::System.ReadOnlySpan<ComponentId> DisabledComponents => _disabledComponents;");
        writer.Line();
        writer.Line($"internal global::System.ReadOnlySpan<{family.RouteType}<TArena>> Routes");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("[global::System.Runtime.CompilerServices.MethodImpl(");
        writer.Indent();
        writer.Line("global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        writer.Unindent();
        writer.Open("get");
        writer.Line("if (!IsCompiled)");
        writer.Indent();
        writer.Line("throw new global::System.InvalidOperationException(\"The query plan has not been compiled by world sealing.\");");
        writer.Unindent();
        writer.Line("return _routes;");
        writer.Close();
        writer.Close();
        writer.Line();
        writer.Open("public void Compile(ArchetypeRegistry<TArena> registry)");
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(registry);");
        writer.Line("if (_compiledArchetypeCount == registry.Count)");
        writer.Indent();
        writer.Line("return;");
        writer.Unindent();
        writer.Line();
        writer.Line("int matchCount = 0;");
        writer.Open("for (int index = 0; index < registry.Count; index++)");
        writer.Line("ArchetypeStorage<TArena> storage = registry.GetStorage(new ArchetypeId((uint)index + 1));");
        writer.Line($"if (Matches(storage, {string.Join(", ", family.Slots.Select(static _ => "out _"))}))");
        writer.Indent();
        writer.Line("matchCount++;");
        writer.Unindent();
        writer.Close();
        writer.Line();
        writer.Line($"var routes = new {family.RouteType}<TArena>[matchCount];");
        writer.Line("int destination = 0;");
        writer.Open("for (int index = 0; index < registry.Count; index++)");
        writer.Line("ArchetypeStorage<TArena> storage = registry.GetStorage(new ArchetypeId((uint)index + 1));");
        writer.Line("if (!Matches(");
        writer.Indent();
        writer.Line("storage,");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            string suffix = index == family.Slots.Length - 1 ? "))" : ",";
            writer.Line($"out int {slot.ColumnParameter}{suffix}");
        }
        writer.Unindent();
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("continue;");
        writer.Close();
        writer.Line();
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"ArchetypeQueryPlanUtilities.ValidateColumn<{slot.TypeName}>(");
            writer.Indent();
            writer.Line($"storage.Columns[{slot.ColumnParameter}],");
            writer.Line($"{slot.ComponentIdProperty},");
            writer.Line($"{slot.FlagsField});");
            writer.Unindent();
        }
        writer.Line($"routes[destination++] = new {family.RouteType}<TArena>(");
        writer.Indent();
        writer.Line("storage,");
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"{family.Slots[index].ColumnParameter},");
        writer.Line("_enabledComponents,");
        writer.Line("_disabledComponents);");
        writer.Unindent();
        writer.Close();
        writer.Line();
        writer.Line("if (destination != routes.Length)");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("ArchetypeQueryPlanUtilities.ThrowQueryInvariant(");
        writer.Indent();
        writer.Line("\"Generated query match counting and route compilation disagree.\");");
        writer.Unindent();
        writer.Close();
        writer.Line("_routes = routes;");
        writer.Line("_compiledArchetypeCount = registry.Count;");
        writer.Close();
        writer.Line();
        writer.Open("public void Release()");
        writer.Line("_routes = [];");
        writer.Line("_compiledArchetypeCount = -1;");
        writer.Close();
        writer.Line();
        writer.Line("private bool Matches(");
        writer.Indent();
        writer.Line("ArchetypeStorage<TArena> storage,");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            string suffix = index == family.Slots.Length - 1 ? ")" : ",";
            writer.Line($"out int {family.Slots[index].ColumnParameter}{suffix}");
        }
        writer.Unindent();
        writer.Open(string.Empty, emitHeader: false);
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"{slot.ColumnParameter} = storage.Store.GetColumnIndex({slot.ComponentIdProperty});");
        }
        writer.Line($"return {string.Join(" &&", family.Slots.Select(static slot => "\n            " + slot.ColumnParameter + " >= 0"))} &&");
        writer.Indent();
        writer.Line("ArchetypeQueryPlanUtilities.SignatureMatches(");
        writer.Indent();
        writer.Line("storage.Signature,");
        writer.Line("_requiredComponents,");
        writer.Line("_excludedComponents);");
        writer.Unindent();
        writer.Unindent();
        writer.Close();
        writer.Close();
    }

    private static void AppendStoreProjection(CodeWriter writer, QueryFamilySpec family)
    {
        writer.Line("internal sealed partial class ArchetypeChunkStore<TArena>");
        writer.Line("where TArena : class, IChunkArenaBackend");
        writer.Open(string.Empty, emitHeader: false);
        writer.Line($"internal {family.BoundChunkType}<{family.TypeParameters}>");
        writer.Indent();
        writer.Line($"GetBound{family.Name}ComponentChunk<{family.TypeParameters}>(");
        writer.Indent();
        writer.Line("int chunkIndex,");
        for (int index = 0; index < family.Slots.Length; index++)
            writer.Line($"int {family.Slots[index].ColumnParameter},");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            string suffix = index == family.Slots.Length - 1 ? ")" : ",";
            writer.Line($"bool {family.Slots[index].IncludeEnableParameter}{suffix}");
        }
        writer.Unindent();
        writer.Unindent();
        AppendUnmanagedConstraints(writer, family);
        writer.Open(string.Empty, emitHeader: false);
        writer.Line("ThrowIfDisposed();");
        writer.Line("if (unchecked((uint)chunkIndex) >= unchecked((uint)_chunks.Length))");
        writer.Indent();
        writer.Line("throw new global::System.ArgumentOutOfRangeException(nameof(chunkIndex));");
        writer.Unindent();
        writer.Line();
        writer.Line("ref readonly ChunkRecord chunk = ref _chunks[chunkIndex];");
        writer.Line("if (chunk.State != ChunkListState.Partial && chunk.State != ChunkListState.Full)");
        writer.Indent();
        writer.Line("throw new global::System.ArgumentException(\"The index does not identify an occupied chunk.\", nameof(chunkIndex));");
        writer.Unindent();
        writer.Line();
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"ref readonly ComponentColumnLayout {slot.ColumnLocal} = ref _columns[{slot.ColumnParameter}];");
        }
        foreach (string condition in BuildPairConditions(family, static slot => slot.ColumnParameter))
            writer.Line($"global::System.Diagnostics.Debug.Assert({condition});");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"global::System.Diagnostics.Debug.Assert({slot.ColumnLocal}.HasData);");
            writer.Line("global::System.Diagnostics.Debug.Assert(");
            writer.Indent();
            writer.Line($"{slot.ColumnLocal}.ElementSizeBytes == global::System.Runtime.CompilerServices.Unsafe.SizeOf<{slot.TypeName}>());");
            writer.Unindent();
            writer.Line($"global::System.Diagnostics.Debug.Assert(!{slot.IncludeEnableParameter} || {slot.ColumnLocal}.HasEnableBits);");
        }
        writer.Line();
        writer.Line("global::System.Span<byte> bytes = _arena.GetChunkBytes(chunk.Handle);");
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"global::System.Span<{slot.TypeName}> {slot.ComponentsParameter} =");
            writer.Indent();
            writer.Line($"global::System.Runtime.InteropServices.MemoryMarshal.Cast<byte, {slot.TypeName}>(");
            writer.Indent();
            writer.Line($"bytes.Slice({slot.ColumnLocal}.DataOffsetBytes, {slot.ColumnLocal}.DataBytes));");
            writer.Unindent();
            writer.Unindent();
        }
        for (int index = 0; index < family.Slots.Length; index++)
        {
            AccessSlot slot = family.Slots[index];
            writer.Line($"global::System.Span<ulong> {slot.EnableParameter} = {slot.IncludeEnableParameter}");
            writer.Indent();
            writer.Line("? global::System.Runtime.InteropServices.MemoryMarshal.Cast<byte, ulong>(");
            writer.Indent();
            writer.Line($"bytes.Slice({slot.ColumnLocal}.EnableBitsOffsetBytes, {slot.ColumnLocal}.EnableBitsBytes))");
            writer.Unindent();
            writer.Line(": global::System.Span<ulong>.Empty;");
            writer.Unindent();
        }
        writer.Line("int rowCount = chunk.RowCount;");
